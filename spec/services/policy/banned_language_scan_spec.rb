# frozen_string_literal: true

require "rails_helper"
require "tmpdir"

RSpec.describe Policy::BannedLanguageScan do
  it "recognizes banned recommendation terms and phrases" do
    violations = described_class.new.scan_text("Buy this stock; Strong Buy; bullish opportunity", path: "test.txt")

    expect(violations.map(&:line)).to all(eq(1))
    expect(violations.first.text).to include("Buy this stock")
  end

  it "allows factual transaction language" do
    violations = described_class.new.scan_text("Reported a purchase and a sale; activity is unusual", path: "test.txt")

    expect(violations).to be_empty
  end

  it "passes the policy-scanned repository paths" do
    expect(described_class.new.violations).to be_empty
  end

  it "also scans the public methodology text stored in a configuration file" do
    Dir.mktmpdir("filingsintel-policy") do |root|
      path = Pathname(root).join("config/activity_methodology.yml")
      path.dirname.mkpath
      path.write("purpose: Strong Buy\n")
      violations = described_class.new(root:).violations
      expect(violations.size).to eq(1)
      expect(violations.first).to have_attributes(path: "config/activity_methodology.yml", line: 1)
    end
  end

  it "scans factual reason templates generated by the scoring services" do
    Dir.mktmpdir("filingsintel-policy") do |root|
      path = Pathname(root).join("app/services/activity_scoring/reasons.rb")
      path.dirname.mkpath
      path.write("reason = 'Strong Buy'\n")
      expect(described_class.new(root:).violations.sole).to have_attributes(
        path: "app/services/activity_scoring/reasons.rb", line: 1)
    end
  end

  it "scans outgoing digest email templates" do
    Dir.mktmpdir("filingsintel-policy") do |root|
      path = Pathname(root).join("app/views/filing_digest_mailer/daily.text.erb")
      path.dirname.mkpath
      path.write("Strong Buy\n")
      expect(described_class.new(root:).violations.sole).to have_attributes(path: "app/views/filing_digest_mailer/daily.text.erb", line: 1)
    end
  end

  it "scans explanation prompts and factual templates" do
    Dir.mktmpdir("filingsintel-policy") do |root|
      %w[app/prompts/filing_explanations/system.txt app/services/filing_explanations/facts.rb].each do |relative|
        path = Pathname(root).join(relative)
        path.dirname.mkpath
        path.write("Strong Buy\n")
      end
      expect(described_class.new(root:).violations.size).to eq(2)
    end
  end
end
